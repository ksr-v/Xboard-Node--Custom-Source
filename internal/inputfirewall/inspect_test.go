func TestSaveParserSupportsRealQuotingCountersAndForeignRules(t *testing.T) {
	m := New("parser")
	text := "# Generated by iptables-save v1.8.9\n*filter\n:INPUT DROP [123:456]\n:OUTPUT ACCEPT [0:0]\n:" + m.name + " - [0:0]\n" +
		"[1:1200] -A INPUT -m comment --comment \"" + m.marker + "\" -j " + m.name + "\n" +
		"-A INPUT -m comment --comment \"foreign spaces \\\"quoted\\\" and \\\\ slash\" -j REJECT\n" +
		"-A OUTPUT -d 169.254.0.0/16 -j ACCEPT\n" +
		"-A " + m.name + " -d 192.0.2.8/32 -p udp -m udp --dport 17443 -m comment --comment \"" + m.marker + "\" -j ACCEPT\n" +
		"-A " + m.name + " -m comment --comment \"" + m.marker + "\" -j RETURN\nCOMMIT\n# Completed\n"
	s, err := inspectSave([]byte(text))
	if err != nil {
		t.Fatal(err)
	}
	all, err := owned(s)
	if err != nil {
		t.Fatal(err)
	}
	if len(all) != 1 || all[m.name].positions[0] != 1 {
		t.Fatal(all)
	}
	if s.input[1][3] != "foreign spaces \"quoted\" and \\ slash" {
		t.Fatal("foreign quoting corrupted", s.input[1])
	}
	r, _ := parseOwned(all[m.name].rules[0], "ACCEPT")
	if r.port != 17443 || r.address != "192.0.2.8/32" {
		t.Fatal(r)
	}
}

func TestSaveMalformedNeverAccepted(t *testing.T) {
	for name, text := range map[string]string{
		"duplicate-table": "*filter\nCOMMIT\n*filter\nCOMMIT\n",
		"unterminated":    "*filter\n:INPUT ACCEPT [0:0]\n",
		"wrong-table":     "*nat\nCOMMIT\n",
		"unknown-chain":   "*filter\n-A INPUT -j ACCEPT\nCOMMIT\n",
		"duplicate-chain": "*filter\n:INPUT ACCEPT [0:0]\n:INPUT DROP [0:0]\nCOMMIT\n",
		"unknown-command": "*filter\n:INPUT ACCEPT [0:0]\n-F INPUT\nCOMMIT\n",
		"bad-quote":       "*filter\n:INPUT ACCEPT [0:0]\n-A INPUT -m comment --comment \"unterminated\nCOMMIT\n",
		"nul":             "*filter\x00\nCOMMIT\n",
		"counter":         "*filter\n:INPUT ACCEPT [x:0]\nCOMMIT\n",
		"commit-outside":  "COMMIT\n",
	} {
		t.Run(name, func(t *testing.T) {
			if _, err := inspectSave([]byte(text)); err != errRules {
				t.Fatal("malformed accepted", err)
			}
		})
	}
	if _, err := inspectSave([]byte(strings.Repeat("#", maxOutput+1))); err != errRules {
		t.Fatal("oversize accepted")
	}
}

func TestStrictOwnedBodyRejectsAdditionalPermissionsAndConditions(t *testing.T) {
	m := New("strict-body")
	d := m.desired(&listener{port: 17443})
	for name, mutate := range map[string]func(*snapshot){
		"wrong-owner": func(s *snapshot) { c := s.chains[m.name]; c.rules[1][3] = New("another").marker; s.chains[m.name] = c },
		"extra-rule": func(s *snapshot) {
			c := s.chains[m.name]
			c.rules = append(c.rules, []string{"-j", "ACCEPT"})
			s.chains[m.name] = c
		},
		"extra-source": func(s *snapshot) {
			c := s.chains[m.name]
			c.rules[0] = append(c.rules[0], "-s", "192.0.2.0/24")
			s.chains[m.name] = c
		},
		"port-range": func(s *snapshot) { c := s.chains[m.name]; c.rules[0][5] = "17443:19443"; s.chains[m.name] = c },
		"duplicate-port": func(s *snapshot) {
			c := s.chains[m.name]
			c.rules[0] = append(c.rules[0], "--dport", "17444")
			s.chains[m.name] = c
		},
		"duplicate-module": func(s *snapshot) {
			c := s.chains[m.name]
			c.rules[0] = append(c.rules[0], "-m", "udp")
			s.chains[m.name] = c
		},
		"conditional-return": func(s *snapshot) {
			c := s.chains[m.name]
			c.rules[1] = append(c.rules[1], "-p", "udp")
			s.chains[m.name] = c
		},
		"widen-destination": func(s *snapshot) {
			c := s.chains[m.name]
			c.rules[0] = append(c.rules[0], "-d", "192.0.2.0/24")
			s.chains[m.name] = c
		},
		"goto": func(s *snapshot) {
			c := s.chains["INPUT"]
			c.rules = append(c.rules, []string{"-m", "comment", "--comment", m.marker, "-g", m.name})
			s.chains["INPUT"] = c
		},
		"conditional-jump": func(s *snapshot) {
			c := s.chains["INPUT"]
			c.rules = append(c.rules, append([]string{"-p", "udp"}, d.jumps[0]...))
			s.chains["INPUT"] = c
		},
		"unmarked-jump": func(s *snapshot) {
			c := s.chains["INPUT"]
			c.rules = append(c.rules, []string{"-j", m.name})
			s.chains["INPUT"] = c
		},
		"foreign-reference": func(s *snapshot) {
			c := s.chains["OUTPUT"]
			c.rules = append(c.rules, d.jumps[0])
			s.chains["OUTPUT"] = c
		},
		"chain-hash": func(s *snapshot) {
			c := s.chains[m.name]
			delete(s.chains, m.name)
			s.chains[chainPrefix+strings.Repeat("0", 20)] = c
		},
	} {
		t.Run(name, func(t *testing.T) {
			s := baseSnapshot()
			s.chains[m.name] = chain{policy: "-", rules: cloneRules(d.rules)}
			mutate(s)
			if _, err := owned(s); err != errOwnership {
				t.Fatal("foreign body accepted", err)
			}
		})
	}
}

func TestOwnedBodyOptionOrderAndUnreferencedStaleChain(t *testing.T) {
	m := New("order")
	s := baseSnapshot()
	s.chains[m.name] = chain{policy: "-", rules: [][]string{
		{"-m", "comment", "--comment", m.marker, "-j", "ACCEPT", "--dport", "17443", "-m", "udp", "-p", "udp"},
		{"-j", "RETURN", "--comment", m.marker, "-m", "comment"},
	}}
	all, err := owned(s)
	if err != nil || len(all[m.name].jumps) != 0 {
		t.Fatal(err)
	}
	if !sameBody(all[m.name], m.desired(&listener{port: 17443})) {
		t.Fatal("equivalent option order not recognized")
	}
}

func TestNativeInputFilterIsRejectedBeforeOpen(t *testing.T) {
	for name, text := range map[string]string{
		"inet":               "{\"nftables\":[{\"chain\":{\"family\":\"inet\",\"table\":\"host\",\"name\":\"input\",\"type\":\"filter\",\"hook\":\"input\"}}]}",
		"firewalld":          "{\"nftables\":[{\"chain\":{\"family\":\"inet\",\"table\":\"firewalld\",\"name\":\"filter_INPUT\",\"type\":\"filter\",\"hook\":\"input\"}}]}",
		"different-ip-table": "{\"nftables\":[{\"chain\":{\"family\":\"ip\",\"table\":\"custom\",\"name\":\"INPUT\",\"type\":\"filter\",\"hook\":\"input\"}}]}",
		"different-ip-chain": "{\"nftables\":[{\"chain\":{\"family\":\"ip\",\"table\":\"filter\",\"name\":\"another\",\"type\":\"filter\",\"hook\":\"input\"}}]}",
		"different-priority": "{\"nftables\":[{\"chain\":{\"family\":\"ip\",\"table\":\"filter\",\"name\":\"INPUT\",\"type\":\"filter\",\"hook\":\"input\",\"prio\":10}}]}",
	} {
		t.Run(name, func(t *testing.T) {
			if err := inspectNft([]byte(text)); err != errUnsupported {
				t.Fatal(err)
			}
		})
	}
	for name, text := range map[string]string{
		"empty":   "{\"nftables\":[]}",
		"compat":  "{\"nftables\":[{\"chain\":{\"family\":\"ip\",\"table\":\"filter\",\"name\":\"INPUT\",\"type\":\"filter\",\"hook\":\"input\",\"prio\":0}},{\"chain\":{\"family\":\"ip6\",\"table\":\"filter\",\"name\":\"INPUT\",\"type\":\"filter\",\"hook\":\"input\",\"prio\":0}}]}",
		"nat":     "{\"nftables\":[{\"chain\":{\"family\":\"inet\",\"table\":\"xbnode_hop_abc\",\"name\":\"prerouting\",\"type\":\"nat\",\"hook\":\"prerouting\"}},{\"chain\":{\"family\":\"ip\",\"table\":\"nat\",\"name\":\"INPUT\",\"type\":\"nat\",\"hook\":\"input\"}}]}",
		"forward": "{\"nftables\":[{\"chain\":{\"family\":\"inet\",\"table\":\"host\",\"name\":\"forward\",\"type\":\"filter\",\"hook\":\"forward\"}}]}",
	} {
		t.Run(name, func(t *testing.T) {
			if err := inspectNft([]byte(text)); err != nil {
				t.Fatal(err)
			}
		})
	}
	for _, text := range []string{"null", "{}", "{\"nftables\":null}", "{\"nftables\":[{\"chain\":null}]}", "{\"nftables\":[{\"chain\":{}}]}"} {
		if inspectNft([]byte(text)) != errRules {
			t.Fatal("malformed nft accepted", text)
		}
	}
}
